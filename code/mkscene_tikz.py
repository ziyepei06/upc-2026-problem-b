"""Export the penalty scene to a TikZ fragment (vector art, real fonts)."""
import numpy as np
import fit6 as F
import paths

B, H, R = 3.66, 2.44, 0.110
SX, SZ, KY = 0.135, 0.85, 0.60   # slight sideways skew, height scale, depth scale
SC = 1.0


def P(*args):
    if len(args) == 3:
        x, y, z = args
    else:
        arr = np.array(args, float).reshape(-1, 3)
        x, y, z = arr[:, 0], arr[:, 1], arr[:, 2]
    x = np.asarray(x, float); y = np.asarray(y, float); z = np.asarray(z, float)
    return np.stack([SC * (y + SX * (x - 5.5)), SC * (SZ * z + KY * x)], axis=-1)


def fmt(p):
    return "(%0.3f,%0.3f)" % (p[0], p[1])


def path(pts):
    return " -- ".join(fmt(p) for p in pts)


out = []
ap = out.append

ap("% generated by mkscene_tikz.py")
# pitch
quad = np.array([[-1.5, -9.0, 0.0], [13.0, -9.0, 0.0],
                 [13.0, 9.0, 0.0], [-1.5, 9.0, 0.0]])
ap("\\fill[green!4!white] %s -- cycle;" % path(P(*quad.T)))
for i, x0 in enumerate(np.arange(-1.5, 13.0, 1.8125)):
    q = np.array([[x0, -9.0, 0.0], [x0 + 1.8125, -9.0, 0.0],
                  [x0 + 1.8125, 9.0, 0.0], [x0, 9.0, 0.0]])
    if i % 2 == 0:
        ap("\\fill[green!8!white] %s -- cycle;" % path(P(*q.T)))
ap("\\draw[pitchline] %s;" % path(P([11, -9.16, 0], [11, 9.16, 0])))
for y in (-9.16, 9.16):
    ap("\\draw[pitchline] %s;" % path(P([5.5, y, 0], [11, y, 0])))
ap("\\draw[pitchline] %s;" % path(P([5.5, -9.16, 0], [5.5, 9.16, 0])))
th = np.linspace(-0.95, 0.95, 40)
arc = P(11 - 9.15 * np.cos(th), 9.15 * np.sin(th), 0 * th)
ap("\\draw[pitchline] %s;" % path(arc))
# goal-mouth backdrop (depth cue)
ap("\\fill[black!6, opacity=0.55] %s -- cycle;"
   % path(P(*np.array([[11.0, -B, 0.0], [11.0 + 1.35, -B, 0.0],
                       [11.0 + 1.35, B, 0.0], [11.0, B, 0.0]]).T)))
# netting (back panel at x = 11 + 1.3, plus the two side panels)
D = 1.35
ap("\\begin{scope}[netline]")
for y in np.linspace(-B, B, 15):
    ap("  \\draw %s;" % path(P([11 + D, y, 0], [11 + D, y, H])))
for z in np.linspace(0.18, H, 7):
    ap("  \\draw %s;" % path(P([11 + D, -B, z], [11 + D, B, z])))
for y in (-B, B):
    for z in np.linspace(0.18, H, 7):
        ap("  \\draw %s;" % path(P([11, y, z], [11 + D, y, z])))
    for x in np.linspace(11, 11 + D, 5)[1:]:
        ap("  \\draw %s;" % path(P([x, y, 0], [x, y, H])))
ap("\\end{scope}")
# goal frame
ap("\\begin{scope}[goalpost]")
for y in (-B, B):
    ap("  \\draw %s;" % path(P([11, y, 0], [11, y, H])))
ap("  \\draw %s;" % path(P([11, -B, H], [11, B, H])))
ap("\\end{scope}")
# entry cloud on the goal plane
nom = np.load(paths.npz("geometry_nominal.npz"))
yz = nom["center_yz"]; w = nom["w"]
ok = np.isfinite(yz).all(axis=1); yz = yz[ok]; w = w[ok] / w[ok].sum()
idx = np.random.default_rng(5).choice(len(yz), 900, replace=False, p=w / w.sum())
qc = P(np.full(len(idx), 10.985), yz[idx, 0], yz[idx, 1])
ap("\\begin{scope}[clouddot, opacity=0.45]")
for p in qc:
    ap("  \\fill %s circle (0.30pt);" % fmt(p))
ap("\\end{scope}")
# trajectory
th_par, _, _, _ = F.fit_map()
cd = th_par[3]; beta = F.beta_vec(th_par)
p = F.R0.copy(); v = th_par[:3].copy()
ps = [p.copy()]
t = 0.0
while t < 0.44:
    p, v = F.rk4_step(p, v, 0.0012, cd, beta)
    t += 0.0012
    ps.append(p.copy())
ps = np.array(ps)
idx_fix = [int(round(0.05 / 0.0012)), int(round(0.10 / 0.0012))]
k = 0
while ps[k][0] <= 11.0:
    k += 1
ps_all = ps[:k]
ps = ps_all[::6]
q = P(ps[:, 0], ps[:, 1], ps[:, 2])
sh = P(ps[:, 0], ps[:, 1], np.zeros(len(ps)))
ap("\\draw[dashed, shadow] %s;" % path(sh))
# soft glow then the flight line
ap("\\draw[draw=flightc, opacity=0.10, line width=4.2pt, line cap=round] %s;"
   % path(q))
ap("\\draw[draw=flightc, opacity=0.22, line width=2.2pt, line cap=round] %s;"
   % path(q))
ap("\\draw[flight] %s;" % path(q))
# ball at the kick and at the plane
q0 = P(ps_all[0, 0], ps_all[0, 1], ps_all[0, 2])
ap("\\shade[ball color=white, draw=ink!60, line width=0.35pt] %s circle (0.55pt);"
   % fmt(q0))
qe = P(11.0, 2.785, 1.945)
ap("\\shade[ball color=white, draw=rustink, line width=0.5pt] %s circle (0.75pt);"
   % fmt(qe))
# the two measured positions
for j, (ii, col, lab) in enumerate([(idx_fix[0], "flightc", "$t=0.05$\\,s"),
                                    (idx_fix[1], "rustink", "$t=0.10$\\,s")]):
    pf = P(ps_all[ii, 0], ps_all[ii, 1], ps_all[ii, 2])
    ap("\\fill[white] %s circle (1.05pt);" % fmt(pf))
    ap("\\draw[%s, line width=0.7pt] %s circle (1.05pt);" % (col, fmt(pf)))
    off = np.array([0.0, -0.30]) if j == 0 else np.array([0.34, -0.16])
    ap("\\node[anchor=north west, font=\\scriptsize, text=%s] at %s {%s};"
       % (col, fmt(pf + off), lab))
# labels
ap("\\node[anchor=north, font=\\footnotesize, text=dimtext] at %s "
   "{$7.32$\\,m};" % fmt(P(11.0, 0.0, 0.0) + np.array([0.10, -0.50])))
ap("\\node[anchor=west, font=\\footnotesize, text=dimtext] at %s "
   "{$2.44$\\,m};" % fmt(P(11.0, B + 0.28, 1.22) + np.array([0.10, 0.0])))
ap("\\node[font=\\footnotesize, text=dimtext] at %s {$11$\\,m};"
   % fmt(P(5.0, -2.7, 0.0)))
ap("\\node[font=\\footnotesize, text=dimtext] at %s {goal plane $x=11$\\,m};"
   % fmt(P(11.0, 0.0, 2.44) + np.array([0.0, 0.62])))
ap("\\node[anchor=west, font=\\footnotesize, text=bluetext] at %s "
   "{$0.40$\\,s of flight};" % fmt(P(7.4, 2.2, 1.15)))
ap("\\node[anchor=north, font=\\footnotesize, text=dimtext] at %s "
   "{penalty mark};" % fmt(P(0.0, 0.0, 0.0) + np.array([0.0, -0.34])))
ap("\\draw[dimarrow] %s -- %s;" % (fmt(P(11, -B, 0)), fmt(P(11, B, 0))))
open("../figures/scene-body.tikz", "w").write("\n".join(out) + "\n")
print("ok", len(out))
