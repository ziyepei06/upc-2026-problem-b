import time, numpy as np, estimators as E, bkick as B
r=(B.SCENARIO[0.05],B.SCENARIO[0.10]); t0=time.time()
e1=E.e1_predict(r)
print("E1: t=%.4f y=%.3f z=%.3f"%(e1['t'],e1['y'],e1['z']))
print("  MC std  %.3f %.3f %.3f | analytic %.3f %.3f %.3f"%(e1['std']['t'],e1['std']['y'],e1['std']['z'],e1['std_analytic']['t'],e1['std_analytic']['y'],e1['std_analytic']['z']))
print("  pct y",np.round(e1['pct']['y'],3)," z",np.round(e1['pct']['z'],3)," P_in %.3f P_c %.3f"%(e1['p_inside'],e1['p_center_inside']))
post=E.PhysicalPosterior(r)
th,lp=post.map(); cov=post.laplace_cov(th); print("MAP",np.round(th,3),"Cd=%.3f"%np.exp(th[3]))
T,Y,Z=post.predict(th[None,:]); print("MAP crossing t=%.4f y=%.3f z=%.3f"%(T[0],Y[0],Z[0]))
t=time.time(); out=post.sample(n=6000,burn=1000,thin=2,cov=cov); print("MCMC %.1fs acc=%.2f"%(time.time()-t,out['acc']))
ch=out['chain']; print("  post mean",np.round(ch.mean(0),3),"sd",np.round(ch.std(0),3))
print("  Cd %.3f+-%.3f |omega| %.1f+-%.1f rad/s (%.2f+-%.2f rev/s)"%(np.exp(ch[:,3]).mean(),np.exp(ch[:,3]).std(),np.linalg.norm(ch[:,4:7],axis=1).mean(),np.linalg.norm(ch[:,4:7],axis=1).std(),np.linalg.norm(ch[:,4:7],axis=1).mean()/6.283,np.linalg.norm(ch[:,4:7],axis=1).std()/6.283))
t=time.time(); T,Y,Z=post.predict(ch); print("pred %.2fs"%(time.time()-t))
s=E.summarize(T,Y,Z); print("  E2 mean",{k:round(v,3) for k,v in s['mean'].items()}); print("  E2 std",{k:round(v,3) for k,v in s['std'].items()})
print("  pct y",np.round(s['pct']['y'],3)," z",np.round(s['pct']['z'],3)," P_in %.3f P_c %.3f"%(s['p_inside'],s['p_center_inside']))
print("total %.1fs"%(time.time()-t0))
