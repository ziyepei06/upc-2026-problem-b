"""Coverage validation of the six-parameter estimator itself (issue 2).

Two arms: (a) truths generated by the SAME six-parameter law; (b) truths with an
extra vertical force the fitted model does not contain (model mismatch).
For each trial: draw truth, synthesise the two fixes at 5 mm noise, fit by
damped Gauss-Newton, sample the posterior by random-walk Metropolis, propagate
to x = 11, and record whether the truth is inside the 90 % marginal intervals.
"""
import json, sys, numpy as np
import fit6 as F

SIG = 0.005
MU = np.array([30., 0., 7., 0.25, 0., 0.])
SD = np.array([15., 15., 10., 0.15, 0.008, 0.008])
LO = np.array([5., -30., 0., 0., -0.08, -0.08])
HI = np.array([60., 30., 30., 1., 0.08, 0.08])


def accel_extra(p, v, cd, beta, extra):
    a = F.accel(p, v, cd, beta)
    if extra is not None:
        a = a + extra
    return a


def rk4_extra(th, times, extra, dt=0.002, r0=F.R0):
    cd = th[3]; beta = F.beta_vec(th)
    p = np.array(r0, float); v = np.array(th[:3], float)
    out = []; t = 0.0
    for tgt in times:
        n = int(round((tgt - t) / dt))
        for _ in range(n):
            k1v = accel_extra(p, v, cd, beta, extra); k1p = v
            k2v = accel_extra(p + .5 * dt * k1p, v + .5 * dt * k1v, cd, beta, extra)
            k2p = v + .5 * dt * k1v
            k3v = accel_extra(p + .5 * dt * k2p, v + .5 * dt * k2v, cd, beta, extra)
            k3p = v + .5 * dt * k2v
            k4v = accel_extra(p + dt * k3p, v + dt * k3v, cd, beta, extra)
            k4p = v + dt * k3v
            p = p + dt / 6 * (k1p + 2 * k2p + 2 * k3p + k4p)
            v = v + dt / 6 * (k1v + 2 * k2v + 2 * k3v + k4v)
        t = tgt; out.append(p.copy())
    return out


def cross_extra(th, extra, dt=0.001, xg=11.0):
    cd = th[3]; beta = F.beta_vec(th)
    p = np.array(F.R0, float); v = np.array(th[:3], float); t = 0.0
    while p[0] < xg and t < 1.2:
        k1v = accel_extra(p, v, cd, beta, extra); k1p = v
        k2v = accel_extra(p + .5 * dt * k1p, v + .5 * dt * k1v, cd, beta, extra)
        k2p = v + .5 * dt * k1v
        k3v = accel_extra(p + .5 * dt * k2p, v + .5 * dt * k2v, cd, beta, extra)
        k3p = v + .5 * dt * k2v
        k4v = accel_extra(p + dt * k3p, v + dt * k3v, cd, beta, extra)
        k4p = v + dt * k3v
        pn = p + dt / 6 * (k1p + 2 * k2p + 2 * k3p + k4p)
        vn = v + dt / 6 * (k1v + 2 * k2v + 2 * k3v + k4v)
        if pn[0] >= xg:
            f = (xg - p[0]) / (pn[0] - p[0])
            return np.array([t + f * dt, p[1] + f * (pn[1] - p[1]), p[2] + f * (pn[2] - p[2])])
        p, v, t = pn, vn, t + dt
    return np.array([np.nan, np.nan, np.nan])


def map_fit(r_obs, times=(0.05, 0.10), iters=40):
    th = np.array([30., 5., 7., 0.25, 0.002, 0.0])
    th = np.clip(th, LO, HI); lam = 1e-2
    def res(th):
        pos = np.array(F.positions(th, times=times)).ravel()
        d = (np.array(r_obs).ravel() - pos) / SIG
        pr = (th - MU) / SD
        return np.concatenate([d, pr])
    r = res(th); cost = r @ r
    for _ in range(iters):
        J = np.zeros((r.size, 6))
        for i in range(6):
            h = 1e-5 * max(1., abs(th[i]))
            tp = th.copy(); tp[i] += h; tm = th.copy(); tm[i] -= h
            J[:, i] = (res(tp) - res(tm)) / (2 * h)
        A = J.T @ J
        g = J.T @ r
        for _ in range(8):
            try:
                step = np.linalg.solve(A + lam * np.diag(np.diag(A) + 1e-9), -g)
            except np.linalg.LinAlgError:
                lam *= 10; continue
            tn = np.clip(th + step, LO, HI)
            rn = res(tn); cn = rn @ rn
            if cn < cost:
                th, r, cost = tn, rn, cn; lam = max(lam * 0.3, 1e-9); break
            lam *= 10
        else:
            break
    return th, cost


def mcmc(th0, r_obs, times=(0.05, 0.10), n=4000, burn=800, thin=2, seed=0):
    rng = np.random.default_rng(seed)
    def lnp(th):
        if np.any(th < LO) or np.any(th > HI):
            return -np.inf
        pos = np.array(F.positions(th, times=times)).ravel()
        d = (np.array(r_obs).ravel() - pos) / SIG
        pr = (th - MU) / SD
        return -0.5 * (d @ d + pr @ pr)
    th = th0.copy(); lp = lnp(th); prop_sd = np.array([0.35, 0.45, 0.35, 0.03, 0.0008, 0.0008])
    keep = []; acc = 0; tot = 0
    for i in range(n):
        cand = th + rng.normal(0, 1, 6) * prop_sd
        lq = lnp(cand)
        if np.log(rng.random()) < lq - lp:
            th, lp = cand, lq; acc += 1
        tot += 1
        if i >= burn and i % thin == 0:
            keep.append(th.copy())
    return np.array(keep), acc / tot


def trial(rng, extra=None):
    truth = rng.normal(MU, SD); truth = np.clip(truth, LO, HI)
    pos = np.array(F.positions(truth, times=(0.05, 0.10)))
    obs = pos + rng.normal(0, SIG, pos.shape)
    # truth crossing
    if extra is None:
        tc = F.cross_plane(truth, dt=0.002)
        if not np.isfinite(tc).all():
            return None
        ty, tz = tc[1], tc[2]
    else:
        tc = cross_extra(truth, extra, dt=0.0015)
        if not np.isfinite(tc).all():
            return None
        ty, tz = tc[1], tc[2]
    th_map, cost = map_fit(obs)
    chain, acc = mcmc(th_map, obs, seed=int(rng.integers(1e6)))
    Y = []; Z = []
    for th in chain:
        c = F.cross_plane(th, dt=0.002)
        if np.isfinite(c).all():
            Y.append(c[1]); Z.append(c[2])
    if len(Y) < 300:
        return None
    Y = np.array(Y); Z = np.array(Z)
    y90 = (np.quantile(Y, .05), np.quantile(Y, .95))
    z90 = (np.quantile(Z, .05), np.quantile(Z, .95))
    ok_y = y90[0] <= ty <= y90[1]; ok_z = z90[0] <= tz <= z90[1]
    inb = (np.abs(Y) <= 3.55) & (Z >= 0.11) & (Z <= 2.33)
    return dict(truth=(float(ty), float(tz)), y90=y90, z90=z90,
                cov_y=bool(ok_y), cov_z=bool(ok_z), cov_2d=bool(ok_y and ok_z),
                width_y=float(y90[1] - y90[0]), width_z=float(z90[1] - z90[0]),
                p_clean=float(inb.mean()), bias_y=float(np.median(Y) - ty),
                bias_z=float(np.median(Z) - tz), acc=float(acc), n_samp=len(Y))


def arm(name, n_tr, extra, seed):
    rng = np.random.default_rng(seed)
    rows = []; i = 0
    while len(rows) < n_tr and i < 3 * n_tr:
        i += 1
        r = trial(rng, extra)
        if r is not None:
            rows.append(r)
        if len(rows) % 10 == 0:
            print(name, len(rows), flush=True)
    return rows


if __name__ == '__main__':
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 60
    out = {}
    same = arm('same-model', n, None, 11)
    out['same'] = same
    mism = arm('mismatch', max(n // 2, 20), np.array([0., 0., 4.0]), 22)
    out['mismatch'] = mism
    for k, rows in out.items():
        if not rows:
            continue
        print(k, 'n=%d' % len(rows),
              'cov_y %.3f cov_z %.3f cov_2d %.3f' % (
                  np.mean([r['cov_y'] for r in rows]),
                  np.mean([r['cov_z'] for r in rows]),
                  np.mean([r['cov_2d'] for r in rows])),
              'width_y %.3f width_z %.3f' % (
                  np.mean([r['width_y'] for r in rows]),
                  np.mean([r['width_z'] for r in rows])),
              'bias_y %+.3f' % np.mean([r['bias_y'] for r in rows]),
              'p_clean %.3f' % np.mean([r['p_clean'] for r in rows]), flush=True)
    json.dump(out, open('../results/valid6.json', 'w'))
    print('written ../results/valid6.json')
